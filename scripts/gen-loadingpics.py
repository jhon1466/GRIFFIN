"""Generates Griffin.GameServer/Services/LoadingPictureConditions.g.cs from the client tables.

    python scripts/gen-loadingpics.py [tables dir]

The loading-screen gallery (LoadingPicData) shows a picture as unlocked when its id is a key of the LoadingPicture quest
counter. The condition of each picture is column 8 (kind) + column 9 (amount), and its target only appears in the
description text (column 7 -> LangPackageTableCnData):

  * 207  "通关<chapter><stage code>"     -> clear any StageData row with that code
  * 1009 "<character>升级至N解锁"        -> own that character at level N or more
  * 402  "指挥官达到N级"                 -> commander level N

Pictures whose target cannot be resolved are reported and left out (they stay locked).
"""
import os
import re
import sys
import collections

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'Griffin.ProtocolSmoke'))
import tabledeep as td  # noqa: E402

TABLES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', 'Griffin', 'bin', 'Release', 'net8.0', 'Resources', 'Tables')
OUT = os.path.join(os.path.dirname(__file__), '..', 'Griffin.GameServer', 'Services', 'LoadingPictureConditions.g.cs')


def rows(name):
    return [td.parse(r) for r in td.rows(os.path.join(TABLES, name + '.bytes'))]


lang = {}
for d in rows('LangPackageTableCnData'):
    v = d.get(2, [b''])[0]
    lang[d[1][0]] = v.decode('utf8', 'ignore') if isinstance(v, bytes) else str(v)


def text_of(msg):
    if isinstance(msg, bytes) and msg[:1] == b'\x08':
        v = s = 0
        i = 1
        while True:
            c = msg[i]
            i += 1
            v |= (c & 0x7F) << s
            if not c & 0x80:
                break
            s += 7
        return lang.get(v, '')
    return ''


by_code = collections.defaultdict(list)
for d in rows('StageData'):
    n = d.get(3, [b''])[0]
    if isinstance(n, bytes):
        by_code[n.decode('utf8', 'ignore').upper()].append(d[1][0])

gun_by_name = {}
for d in rows('GunData'):
    if d.get(2):
        name = text_of(d[2][0]).strip()
        if name:
            gun_by_name.setdefault(name, d[1][0])

stages, levels, gun_levels, missing = {}, {}, {}, []
version = open(os.path.join(TABLES, 'version.txt')).read().strip() if os.path.exists(os.path.join(TABLES, 'version.txt')) else '?'
for d in rows('LoadingPicData'):
    pid = d[1][0]
    kind = d.get(8, [0])[0]
    amount = d.get(9, [0])[0]
    t = re.sub(r'<[^>]+>', '', text_of(d[7][0]) if d.get(7) else '').strip()
    if kind == 402 or re.match(r'^指挥官达到(\d+)级$', t):
        m = re.match(r'^指挥官达到(\d+)级$', t)
        levels[pid] = int(m.group(1)) if m else amount
        continue
    m = re.match(r'^(.+?)升级至(\d+)解锁$', t)
    if kind == 1009 and m:
        gun = gun_by_name.get(m.group(1).strip())
        if gun:
            gun_levels[pid] = (gun, int(m.group(2)))
            continue
    if kind == 207:
        # The stage code ends the text: AA-1-11, SL-2-4, 3-10, QS-1... ("困难" means the HD- variant).
        m = re.search(r'([A-Z]{1,3}-)?(\d+(?:-\d+)*)$', re.sub(r'后?解锁$', '', t))
        if m:
            code = (m.group(1) or '') + m.group(2)
            names = ['HD-' + code] if '困难' in t and re.fullmatch(r'\d+-\d+', code) else [code]
            ids = sorted({s for n in names for s in by_code.get(n.upper(), [])})
            if ids:
                stages[pid] = ids
                continue
    missing.append((pid, kind, t))

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(f'// <auto-generated> by scripts/gen-loadingpics.py from the client tables {version}. Do not edit. </auto-generated>\n')
    f.write('namespace Griffin.GameServer.Services\n{\n')
    f.write('    internal static class LoadingPictureConditions\n    {\n')
    f.write('        /// <summary>Picture id -> commander level that unlocks it.</summary>\n')
    f.write('        public static readonly (uint Id, uint Level)[] Levels =\n        [\n')
    for k in sorted(levels):
        f.write(f'            ({k}, {levels[k]}),\n')
    f.write('        ];\n\n')
    f.write('        /// <summary>Picture id -> (character, level): unlocked when the account owns that character at that level or more.</summary>\n')
    f.write('        public static readonly (uint Id, uint Gun, uint Level)[] GunLevels =\n        [\n')
    for k in sorted(gun_levels):
        f.write(f'            ({k}, {gun_levels[k][0]}, {gun_levels[k][1]}),\n')
    f.write('        ];\n\n')
    f.write('        /// <summary>Picture id -> stages of which clearing ANY unlocks it.</summary>\n')
    f.write('        public static readonly (uint Id, uint[] Stages)[] Stages =\n        [\n')
    for k in sorted(stages):
        f.write(f'            ({k}, [{", ".join(str(x) for x in stages[k])}]),\n')
    f.write('        ];\n    }\n}\n')

print(f'levels {len(levels)}, character levels {len(gun_levels)}, stages {len(stages)}, unresolved {len(missing)} -> {os.path.normpath(OUT)}')
for pid, kind, t in missing:
    print('  unresolved', pid, kind, t)
