"""Generates Griffin.Common.Proto/Handlers/PacketHandlerBases.g.cs: the packet-handler base classes of the game protocol.

    python tools/gen-handlers.py

The services of protos/GF2_deobfuscated.proto list, one per request, `rpc HandleX (CS_X) returns (...)`. Each service becomes an abstract
class `<Name>HandlerBase : IPacketHandler` with one virtual method per rpc, marked with `[PacketHandler(MsgId.MsgCsX)]` (the request type
with `CS_` read as `Cs` and without underscores, prefixed by `Msg`; the enum is Griffin.Common/Protocol/MsgId.cs). The message classes
themselves come from protoc (Grpc.Tools) at build time; only this file is written by hand-made generation and is committed, so building
needs neither Python nor any other tool. Run it again after the protos change.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
PROTO = os.path.join(ROOT, 'Griffin.Common.Proto', 'protos', 'GF2_deobfuscated.proto')
OUT = os.path.join(ROOT, 'Griffin.Common.Proto', 'Handlers', 'PacketHandlerBases.g.cs')

text = open(PROTO, encoding='utf-8').read()
services = []
for m in re.finditer(r'^service\s+(\w+)\s*\{(.*?)^\}', text, re.S | re.M):
    rpcs = re.findall(r'rpc\s+(\w+)\s*\(\s*(\w+)\s*\)', m.group(2))
    services.append((m.group(1), rpcs))


def msg_id(request):
    return 'Msg' + re.sub(r'^CS_', 'Cs', request).replace('_', '')


os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// <auto-generated> by tools/gen-handlers.py from protos/GF2_deobfuscated.proto. Do not edit. </auto-generated>\n')
    f.write('#pragma warning disable 1591\n\n')
    f.write('namespace Griffin.Common.Proto\n{\n')
    count = 0
    for name, rpcs in services:
        base = re.sub(r'Service$', '', name) + 'HandlerBase'
        f.write(f'    /// <summary>Handlers of {name}: one virtual method per request, dispatched by message id.</summary>\n')
        f.write(f'    public abstract partial class {base} : global::Griffin.Common.Packets.IPacketHandler\n    {{\n')
        for method, request in rpcs:
            count += 1
            f.write(f'        [global::Griffin.Common.Packets.PacketHandlerAttribute(global::Griffin.Common.Protocol.MsgId.{msg_id(request)})]\n')
            f.write(f'        public virtual void {method}(global::Griffin.Common.Proto.{request} request, global::Griffin.Common.Networking.Connection connection)\n')
            f.write('        {\n')
            f.write(f'            throw new global::System.NotImplementedException("{method} is not implemented.");\n')
            f.write('        }\n\n')
        f.write('    }\n\n')
    f.write('}\n')

print(f'{len(services)} services, {count} handlers -> {os.path.normpath(OUT)}')
