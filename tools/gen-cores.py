"""Generates Griffin.GameServer/Services/RemouldingCores.g.cs from the client tables.

    python tools/gen-cores.py [tables dir]

Every character has ONE remoulding core (CoreData: 68 rows, 68 characters). CoreData has no column naming the character, only its
name ("火力核心·<character name>", "支援核心·..."), so the core of a character is the row whose name after the first "·" is the
name of the character (GunData column 2, a LangPackageTableCnData text).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tabledeep as td  # noqa: E402

TABLES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', 'Griffin', 'bin', 'Release', 'net8.0', 'Resources', 'Tables')
OUT = os.path.join(os.path.dirname(__file__), '..', 'Griffin.GameServer', 'Services', 'RemouldingCores.g.cs')


def rows(name):
    return [td.parse(r) for r in td.rows(os.path.join(TABLES, name + '.bytes'))]


def text_id(msg):
    if isinstance(msg, bytes) and msg[:1] == b'\x08':
        v = s = 0
        i = 1
        while True:
            c = msg[i]
            i += 1
            v |= (c & 0x7F) << s
            if not c & 0x80:
                break
            s += 7
        return v
    return 0


lang = {}
for d in rows('LangPackageTableCnData'):
    v = d.get(2, [b''])[0]
    lang[d[1][0]] = v.decode('utf8', 'ignore') if isinstance(v, bytes) else str(v)

gun_by_name = {}
for g in rows('GunData'):
    gun_by_name.setdefault(lang.get(text_id(g[2][0]), ''), g[1][0])

pairs = []
for c in sorted(rows('CoreData'), key=lambda r: r[1][0]):
    name = lang.get(text_id(c[2][0]), '').split('·', 1)[-1]
    gun = gun_by_name.get(name)
    if gun:
        pairs.append((gun, c[1][0]))

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// <auto-generated> by tools/gen-cores.py from the client tables 1189260. Do not edit. </auto-generated>\n')
    f.write('namespace Griffin.GameServer.Services\n{\n    public static partial class RemouldingCores\n    {\n')
    f.write('        /// <summary>Character (GunData id) -> its remoulding core (CoreData id).</summary>\n')
    f.write('        private static readonly (uint Gun, uint Core)[] Pairs =\n        [\n')
    for gun, core in sorted(pairs):
        f.write(f'            ({gun}, {core}),\n')
    f.write('        ];\n    }\n}\n')

print(f'{len(pairs)} characters with a core -> {os.path.normpath(OUT)}')
