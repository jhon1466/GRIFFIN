"""Generates Griffin.GameServer/Services/AchievementConditions.g.cs from the client tables.

    python tools/gen-achievements.py [tables dir]

The client unlocks chapters, activity stories and many features with ACHIEVEMENTS (ChapterData column 16 lists achievement ids;
the client asks Quest counters of type Achievement whether the id is complete). The condition of an achievement is only
written as text (AchievementDetailData column 6 -> LangPackageTableCnData), so this script reads that text once and writes
the supported kinds as data:

  * character level ("人形升至N级" ladders of the talent trees; "<name>升级至N解锁" of the dormitory poses/personal stories)
  * commander level ("指挥官达到N级", "指挥官等级N", "等级达到N级")
  * stage clear ("完成剧情战役普通1-8", "完成剧情战役困难2-5" -> stage HD-2-5, "通关剧情战役1-8", "完成活动剧情普通N-N"...)
    resolved to every StageData row with that name (any of them cleared completes it)

Everything else (gun levels, logins, purchases...) has no server-side progress and is not generated.
"""
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tabledeep as td  # noqa: E402

TABLES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', 'Griffin', 'bin', 'Release', 'net8.0', 'Resources', 'Tables')
OUT = os.path.join(os.path.dirname(__file__), '..', 'Griffin.GameServer', 'Services', 'AchievementConditions.g.cs')


def rows(name):
    return [td.parse(r) for r in td.rows(os.path.join(TABLES, name + '.bytes'))]


lang = {}
for d in rows('LangPackageTableCnData'):
    v = d.get(2, [b''])[0]
    lang[d[1][0]] = v.decode('utf8', 'ignore') if isinstance(v, bytes) else str(v)


def text_of(msg):
    """A LanguageStringData column is a nested {1: text id}."""
    if isinstance(msg, bytes) and msg[:1] == b'\x08':
        v = s = 0
        i = 1
        while True:
            c = msg[i]
            i += 1
            v |= (c & 0x7F) << s
            if not c & 0x80:
                break
            s += 7
        return lang.get(v, '')
    return ''


by_name = collections.defaultdict(list)
for d in rows('StageData'):
    n = d.get(3, [b''])[0]
    if isinstance(n, bytes):
        by_name[n.decode('utf8', 'ignore').upper()].append(d[1][0])

levels = {}
stages = {}
gun_levels = {}

# "人形升至N级" ladders are numbered by SERIES (id 4 SSS NN) and the series of a character is NOT its id: the points of its talent
# tree (SquadTalentGroupData column 5) name the series and SquadTalentGunData column 8 gives the tree of each character.
series_owner = {}
tree_series = {}
for d in rows('SquadTalentGroupData'):
    cond = d.get(5, [0])[0]
    if cond:
        tree_series.setdefault(d[1][0] // 1000000, set()).add(cond // 100 % 1000)
for d in rows('SquadTalentGunData'):
    for s in tree_series.get(d.get(8, [0])[0], ()):
        series_owner.setdefault(s, []).append(d[1][0])

for d in rows('AchievementDetailData'):
    aid = d[1][0]
    if not d.get(6):
        continue
    t = re.sub(r'<[^>]+>', '', text_of(d[6][0])).strip()
    m = re.match(r'^人形升至(\d+)级$', t)
    if m and 400000 <= aid <= 499999:
        for gun in series_owner.get((aid // 100) % 1000, [1000 + (aid // 100) % 1000]):
            gun_levels.setdefault(aid, []).append((gun, int(m.group(1))))
        continue
    # "<character>升级至N解锁" (id 4 GGGG K): dormitory poses and personal stories of the character GGGG unlock when it reaches level N
    m = re.match(r'^.+升级至(\d+)解锁$', t)
    if m and 400000 <= aid <= 499999:
        gun_levels.setdefault(aid, []).append(((aid // 10) % 10000, int(m.group(1))))
        continue
    m = (re.match(r'^指挥官(?:等级)?达到(\d+)级$', t) or re.match(r'^指挥官等级(\d+)$', t) or re.match(r'^等级达到(\d+)级$', t))
    if m:
        levels[aid] = int(m.group(1))
        continue
    m = re.match(r'^(?:完成|通关)(?:剧情战役|活动剧情|活动战役)(普通|困难)?([A-Z0-9]+(?:-[A-Z0-9]+)+)$', t)
    if m:
        hard = m.group(1) == '困难'
        code = m.group(2)
        names = ['HD-' + code] if hard and re.fullmatch(r'\d+-\d+', code) else [code]
        ids = sorted({s for n in names for s in by_name.get(n, [])})
        if ids:
            stages[aid] = ids

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// <auto-generated> by tools/gen-achievements.py from the client tables 1189260. Do not edit. </auto-generated>\n')
    f.write('namespace Griffin.GameServer.Services\n{\n')
    f.write('    internal static class AchievementConditions\n    {\n')
    f.write('        /// <summary>Achievement id -> commander level that completes it.</summary>\n')
    f.write('        public static readonly (uint Id, uint Level)[] Levels =\n        [\n')
    for k in sorted(levels):
        f.write(f'            ({k}, {levels[k]}),\n')
    f.write('        ];\n\n')
    f.write('        /// <summary>Achievement id -> (character, level): complete when the account owns that character at that level or more.</summary>\n')
    f.write('        public static readonly (uint Id, uint Gun, uint Level)[] GunLevels =\n        [\n')
    for k in sorted(gun_levels):
        for gun, level in gun_levels[k]:
            f.write(f'            ({k}, {gun}, {level}),\n')
    f.write('        ];\n\n')
    f.write('        /// <summary>Achievement id -> stages of which clearing ANY completes it.</summary>\n')
    f.write('        public static readonly (uint Id, uint[] Stages)[] Stages =\n        [\n')
    for k in sorted(stages):
        f.write(f'            ({k}, [{", ".join(str(x) for x in stages[k])}]),\n')
    f.write('        ];\n    }\n}\n')

print(f'level achievements: {len(levels)}; stage achievements: {len(stages)} -> {os.path.normpath(OUT)}')
